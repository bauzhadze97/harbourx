function defaultCurrencyForCountry($countryCode) {
    $countryCode = strtoupper(trim((string)$countryCode));
    $countries = countryCurrencyMap();
    return $countries[$countryCode][1] ?? 'USD';
}

function countryName($countryCode) {
    $countryCode = strtoupper(trim((string)$countryCode));
    $countries = countryCurrencyMap();
    return $countries[$countryCode][0] ?? '';
}

function cleanCountryCode($value) {
    $countryCode = strtoupper(trim((string)$value));
    return array_key_exists($countryCode, countryCurrencyMap()) ? $countryCode : '';
}

function renderCountryOptions($selected = '') {
    $selected = cleanCountryCode($selected);
    $html = '<option value="">Choose country</option>';
    foreach (countryCurrencyMap() as $code => $details) {
        $isSelected = $code === $selected ? ' selected' : '';
        $html .= '<option value="' . htmlspecialchars($code) . '" data-currency="' . htmlspecialchars($details[1]) . '"' . $isSelected . '>'
            . htmlspecialchars($details[0]) . '</option>';
    }
    return $html;
}

function renderCurrencyOptions($selected = 'USD') {
    $selected = strtoupper(trim((string)$selected));
    $currencies = currencyNames();
    foreach (countryCurrencyMap() as $details) {
        if (!isset($currencies[$details[1]])) $currencies[$details[1]] = $details[1];
    }
    ksort($currencies);
    $html = '';
    foreach ($currencies as $code => $name) {
        $isSelected = $code === $selected ? ' selected' : '';
        $html .= '<option value="' . htmlspecialchars($code) . '"' . $isSelected . '>'
            . htmlspecialchars($code . ' - ' . $name) . '</option>';
    }
    if ($selected !== '' && !isset($currencies[$selected])) {
        $html = '<option value="' . htmlspecialchars($selected) . '" selected>' . htmlspecialchars($selected) . '</option>' . $html;
    }
    return $html;
}

